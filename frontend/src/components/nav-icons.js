export function getNavItemIcon(path, label = '') {
  let key = 'files';
  if (path === '/can-bo') key = 'dashboard';
  else if (path === '/can-bo/ho-so') key = 'files';
  else if (path.includes('status=1')) key = 'inbox';
  else if (path.includes('status=2')) key = 'edit';
  else if (path.includes('status=12')) key = 'rework';
  else if (path.includes('status=5')) key = 'alert';
  else if (path.includes('status=4')) key = 'checkShield';
  else if (path.includes('status=9') && label.includes('phê duyệt')) key = 'checkCircle';
  else if (path.includes('status=9')) key = 'send';
  else if (path.includes('status=10')) key = 'checkDone';
  else if (path.includes('/bao-cao')) key = 'chart';
  else if (path.includes('/danh-muc-thu-tuc')) key = 'book';
  else if (path.includes('/quan-tri/nguoi-dung')) key = 'users';
  else if (path.includes('/quan-tri/can-bo')) key = 'staff';
  else if (path.includes('/quan-tri/linh-vuc')) key = 'grid';

  const span = document.createElement('span');
  span.style.display = 'inline-flex';
  span.style.alignItems = 'center';
  span.style.justifyContent = 'center';
  span.style.flexShrink = '0';
  span.style.width = '16px';
  span.style.height = '16px';
  span.innerHTML = `<svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${ICONS[key] || ICONS.files}</svg>`;
  return span;
}
